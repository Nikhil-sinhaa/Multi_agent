def weather_agent(state: TravelState):
    city = extract_destination(state['user_query'])
    weather_data = asyncio.run(
        weather_mcp_search(city)
    )
    forecast_data = asyncio.run(
        forecast_mcp_search(city)
    )

    # Build a rich, LLM-interpreted weather briefing
    weather_prompt = WEATHER_SUMMARY_PROMPT.format(
        city=city,
        query=state['user_query'],
        weather_data=str(weather_data)[:3000],
        forecast_data=str(forecast_data)[:3000]
    )
    weather_response = llm.invoke([
        SystemMessage(
            content=(
                "You are a professional meteorologist and travel climate advisor. "
                "You translate raw weather API data into clear, actionable, traveller-friendly briefings. "
                "Always include specific numbers (temperatures, percentages, UV index). "
                "Never give vague descriptions -- every claim must be backed by the data provided."
            )
        ),
        HumanMessage(content=weather_prompt)
    ])

    return {
        "weather_results": weather_response.content,
        "messages": [
            AIMessage(content="Weather briefing generated")
        ],
        "llm_calls": state.get("llm_calls", 0) + 1
    }

