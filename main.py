async def search_fares(details: dict, query: str) -> str:
    """Web-search real fares/airlines for this trip's route and dates (Tavily)."""
    origin, dest = details.get("origin"), details.get("destination")
    route = f"{origin} to {dest}" if origin and dest else query
    when = f" {details['start_date']}" if details.get("start_date") else ""
    searches = [
        f"cheapest flight fares {route}{when} price economy",
        f"airlines direct flights {route} duration typical price",
    ]
    parts = []
    for q in searches:
        try:
            parts.append(f"## Search: {q}\n{await tavily_mcp_search(q)}")
        except Exception as e:
            parts.append(f"## Search: {q}\n(search failed: {e})")
    return "\n\n".join(parts)


