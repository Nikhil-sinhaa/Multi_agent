def flight_agent(state: TravelState):
    print("\nINSIDE FLIGHT AGENT\n")
    query = state["user_query"]

    try:
        airports = asyncio.run(
            aviation_mcp_call(
                "list_airports"
            )
        )
        airlines = asyncio.run(
            aviation_mcp_call(
                "list_airlines"
            )
        )

        prompt = FLIGHT_AGENT_PROMPT.format(
            query=query,
            airport_data=str(airports)[:3000],
            airline_data=str(airlines)[:3000]
        )

        response = llm.invoke([
            SystemMessage(
                content=(
                    "You are a senior flight planning specialist with deep expertise in global aviation routes, "
                    "airline pricing strategies, airport logistics, and travel hacking. "
                    "You provide structured, data-driven, and actionable flight guidance. "
                    "Always be specific with prices, durations, and booking windows. "
                    "Format responses with clear headers and bullet points for easy reading."
                )
            ),
            HumanMessage(content=prompt)
        ])

        # Fixed: added return statement (function was missing return, silently returning None)
        return {
            "flight_results": response.content,
            "messages": [
                AIMessage(content="Flight results fetched")
            ],
            "llm_calls": state.get("llm_calls", 0) + 1
        }

    except Exception as e:
        return {
            "flight_results": f"Error fetching flight data: {str(e)}",
            "messages": [AIMessage(content="Flight agent encountered an error.")],
            "llm_calls": state.get("llm_calls", 0) + 1
        }

