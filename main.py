# flight_agent fans out to hotel and weather
graph.add_edge("flight_agent", "hotel_agent")    # fan-out  
graph.add_edge("flight_agent", "weather_agent")  # fan-out  

# Fan-in: hotel, weather, and train all converge into itinerary
