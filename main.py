logger = logging.getLogger(__name__)


def safe_agent(name: str, result_key: str):
    """Keep one failing agent (API outage, rate limit, ...) from crashing the whole run.

    On failure the agent's result field holds an error note, so downstream agents
    and the UI still get something to work with. No LLM call is counted for it.
    """
    def decorator(fn):
        @functools.wraps(fn)
        def wrapper(state: TravelState):
            try:
                return fn(state)
            except Exception as e:
                logger.exception("%s failed", name)
                return {
                    result_key: f"Error in {name}: {e}",
                    "messages": [AIMessage(content=f"{name} encountered an error.")],
                    "llm_calls": 0,
                }
        return wrapper
    return decorator

TRIP_FIELDS = {
    "origin": "Departing from",
    "destination": "Destination",
    "start_date": "Start date",
    "num_days": "Trip length (days)",
    "budget": "Budget",
    "travellers": "Travellers",
}


def _blank_trip_details() -> dict:
    return {k: "" for k in TRIP_FIELDS}


def extract_trip_details(query: str) -> dict:
    """One LLM call that pulls the structured trip details out of a free-text request.

    Anything not stated in the request comes back as "" -- nothing is guessed.
    Never raises: on any failure every field is blank.
    """
    prompt = f"""Extract trip details from the traveller's request.
Today's date is {date.today().isoformat()}.

Request:
{query}

Reply with ONLY a JSON object with exactly these keys:
"origin" (city/country the traveller departs from), "destination" (main city or country),
"start_date" (YYYY-MM-DD if a specific date is given, otherwise the stated month/season, e.g. "March 2027"),
"num_days" (number), "budget" (with currency, e.g. "INR 200000"), "travellers" (number or description, e.g. "2 adults"),
"train_applicable" (true if travelling between origin and destination by train is realistic, i.e. they are connected
by land/rail; false if they are separated by sea or are on different continents, e.g. India to Japan; true if unsure).
Use "" for anything the request does not state (except train_applicable). Do not guess."""
    details = _blank_trip_details()
    try:
        text = llm.invoke(prompt).content
        match = re.search(r"\{.*\}", text, re.DOTALL)
        data = json.loads(match.group(0)) if match else {}
        for key in details:
            value = data.get(key)
            if value is not None:
                details[key] = str(value).strip()
        if data.get("train_applicable") is not None:
            details["train_applicable"] = str(data["train_applicable"]).strip().lower()
    except Exception:
        logger.exception("trip detail extraction failed")
    return details


def train_applicable(details: dict) -> bool:
    """Rail is assumed to apply unless extraction explicitly said it doesn't."""
    return str((details or {}).get("train_applicable", "true")).lower() not in ("false", "no", "0")


def missing_trip_fields(details: dict) -> list[str]:
    return [k for k in TRIP_FIELDS if not (details or {}).get(k)]


def trip_brief(state: TravelState) -> str:
    """The traveller's request plus the structured details, for use in every agent prompt."""
    query = state.get("user_query", "")
    details = state.get("trip_details") or {}
    lines = [f"- {label}: {details[k]}" for k, label in TRIP_FIELDS.items() if details.get(k)]
    if not lines:
        return query
    return query + "\n\nConfirmed trip details:\n" + "\n".join(lines)


def extract_details_agent(state: TravelState):
    """First pipeline step. Skipped when the UI already collected the details."""
    if any((state.get("trip_details") or {}).values()):
        return {"llm_calls": 0}
    return {
        "trip_details": extract_trip_details(state["user_query"]),
        "messages": [AIMessage(content="Trip details extracted")],
        "llm_calls": 1,
    }


